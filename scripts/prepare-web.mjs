#!/usr/bin/env node
// Copy a locked npm dependency into the static site. No bundler or CDN at runtime.
import { readFile, readdir, copyFile, mkdir, rename, rm, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { locales } from '../web/i18n/index.js';
const root = fileURLToPath(new URL('../', import.meta.url));

// Real directories let GitHub Pages serve language URLs without SPA rewrites.
// Keep the app and its assets shared; only the HTML entry points are copied.
const html = await readFile(path.join(root, 'web/index.html'), 'utf8');
for (const locale of locales) {
  const directory = path.join(root, 'web', locale);
  await mkdir(directory, { recursive: true });
  await writeFile(
    path.join(directory, 'index.html'),
    html
      .replace('<html lang="en">', `<html lang="${locale}">`)
      .replace(/((?:src|href)=")\.\/(?!")/g, '$1../'),
  );
}
console.log(`Prepared language entry points (${locales.join(', ')})`);

const source = path.join(root, 'node_modules/@bjorn3/browser_wasi_shim');
const target = path.join(root, 'web/vendor/browser_wasi_shim');
const pkg = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'));
const installed = JSON.parse(await readFile(path.join(source, 'package.json'), 'utf8'));
if (installed.version !== pkg.dependencies['@bjorn3/browser_wasi_shim'])
  throw new Error('WASI shim version differs from package.json; run npm ci --ignore-scripts');
const staging = `${target}.staging`;
await rm(staging, { recursive: true, force: true });
await mkdir(staging, { recursive: true });
for (const file of await readdir(path.join(source, 'dist')))
  if (file.endsWith('.js'))
    await copyFile(path.join(source, 'dist', file), path.join(staging, file));
for (const file of ['LICENSE-APACHE', 'LICENSE-MIT'])
  await copyFile(path.join(source, file), path.join(staging, file));
// This directory is generated only; local runtime adaptations belong in web/runtime.
await rm(target, { recursive: true, force: true });
await rename(staging, target);
console.log(`Prepared browser_wasi_shim ${installed.version}`);

// Prism is a presentation dependency, separate from the compiler WASM.
const prism = path.join(root, 'node_modules/prismjs');
const prismTarget = path.join(root, 'web/vendor/prismjs');
const prismPackage = JSON.parse(await readFile(path.join(prism, 'package.json'), 'utf8'));
if (prismPackage.version !== pkg.dependencies.prismjs)
  throw new Error('Prism version differs from package.json; run npm ci --ignore-scripts');
await mkdir(prismTarget, { recursive: true });
for (const name of ['core', 'clike', 'ruby', 'crystal', 'llvm'])
  await copyFile(
    path.join(prism, `components/prism-${name}.min.js`),
    path.join(prismTarget, `prism-${name}.min.js`),
  );
await copyFile(path.join(prism, 'LICENSE'), path.join(prismTarget, 'LICENSE'));
console.log(`Prepared Prism ${prismPackage.version} (Crystal and LLVM grammars)`);

// Lucide ships 1,500+ icons; only the glyphs named in the UI vocabulary are copied.
const { lucideNames } = await import(new URL('../web/ui/icon-names.js', import.meta.url));
const lucide = path.join(root, 'node_modules/lucide-static');
const lucideTarget = path.join(root, 'web/vendor/lucide');
const lucidePackage = JSON.parse(await readFile(path.join(lucide, 'package.json'), 'utf8'));
if (lucidePackage.version !== pkg.dependencies['lucide-static'])
  throw new Error('Lucide version differs from package.json; run npm ci --ignore-scripts');
const nodes = JSON.parse(await readFile(path.join(lucide, 'icon-nodes.json'), 'utf8'));
const attributes = (attrs) =>
  Object.entries(attrs)
    .map(([key, value]) => ` ${key}="${value}"`)
    .join('');
const glyphs = [...new Set(Object.values(lucideNames))].sort().map((name) => {
  if (!nodes[name]) throw new Error(`Lucide has no icon named ${name}`);
  const markup = nodes[name].map(([tag, attrs]) => `<${tag}${attributes(attrs)}/>`).join('');
  return `  '${name}': '${markup}',`;
});
await mkdir(lucideTarget, { recursive: true });
await writeFile(
  path.join(lucideTarget, 'icons.js'),
  `// Generated by scripts/prepare-web.mjs from lucide-static ${lucidePackage.version} (ISC). Do not edit.\n` +
    `// Inner markup of 24×24 stroke icons; web/ui/icons.js wraps them in <svg>.\n` +
    `export default {\n${glyphs.join('\n')}\n};\n`,
);
await copyFile(path.join(lucide, 'LICENSE'), path.join(lucideTarget, 'LICENSE'));
console.log(`Prepared Lucide ${lucidePackage.version} (${glyphs.length} icons)`);
